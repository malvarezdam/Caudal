impl Texts {
    /// "Cada mes", "Cada 2 semanas", "Último día de cada mes"…
    pub fn frequency(&self, frequency: Frequency, interval: i32, last_day: bool) -> String {
        let es = std::ptr::eq(self, &ES);
        let n = interval.max(1);
        if last_day && frequency == Frequency::Monthly {
            return match (es, n) {
                (true, 1) => "Último día de cada mes".into(),
                (true, n) => format!("Último día cada {n} meses"),
                (false, 1) => "Last day of every month".into(),
                (false, n) => format!("Last day every {n} months"),
            };
        }
        let (one, many) = match (frequency, es) {
            (Frequency::Daily, true) => ("Cada día", "días"),
            (Frequency::Weekly, true) => ("Cada semana", "semanas"),
            (Frequency::Monthly, true) => ("Cada mes", "meses"),
            (Frequency::Yearly, true) => ("Cada año", "años"),
            (Frequency::Daily, false) => ("Every day", "days"),
            (Frequency::Weekly, false) => ("Every week", "weeks"),
            (Frequency::Monthly, false) => ("Every month", "months"),
            (Frequency::Yearly, false) => ("Every year", "years"),
        };
        match (n, es) {
            (1, _) => one.into(),
            (n, true) => format!("Cada {n} {many}"),
            (n, false) => format!("Every {n} {many}"),
        }
    }

    pub fn frequency_unit(&self, frequency: Frequency) -> &'static str {
        let es = std::ptr::eq(self, &ES);
        match (frequency, es) {
            (Frequency::Daily, true) => "Diaria",
            (Frequency::Weekly, true) => "Semanal",
            (Frequency::Monthly, true) => "Mensual",
            (Frequency::Yearly, true) => "Anual",
            (Frequency::Daily, false) => "Daily",
            (Frequency::Weekly, false) => "Weekly",
            (Frequency::Monthly, false) => "Monthly",
            (Frequency::Yearly, false) => "Yearly",
        }
    }

    pub fn direction(&self, direction: DebtDirection) -> &'static str {
        match direction {
            DebtDirection::OwedToMe => self.owed_to_me,
            DebtDirection::IOwe => self.i_owe,
        }
    }
}

