#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Lang {
    #[default]
    Es,
    En,
}

impl Lang {
    pub const ALL: [Lang; 2] = [Lang::Es, Lang::En];

    pub fn code(self) -> &'static str {
        match self {
            Lang::Es => "es",
            Lang::En => "en",
        }
    }

    /// Acepta `es`, `es-CL`, `en_US`… Lo desconocido cae en español.
    pub fn parse(code: &str) -> Lang {
        if code.to_ascii_lowercase().starts_with("en") {
            Lang::En
        } else {
            Lang::Es
        }
    }

    pub fn name(self) -> &'static str {
        match self {
            Lang::Es => "Español",
            Lang::En => "English",
        }
    }

    pub(crate) fn decimal_separator(self) -> char {
        match self {
            Lang::Es => ',',
            Lang::En => '.',
        }
    }

    pub(crate) fn thousands_separator(self) -> char {
        match self {
            Lang::Es => '.',
            Lang::En => ',',
        }
    }
}

pub fn texts(lang: Lang) -> &'static Texts {
    match lang {
        Lang::Es => &ES,
        Lang::En => &EN,
    }
}

